import { retrieveRelevantChunks } from "./retrieve.js";

const LLM_URL = process.env.LLM_URL ?? "http://localhost:11434/api/chat";

const LLM_MODEL = "qwen3.5:9b";

export async function answerFromDocuments(
  userId: number,
  question: string,
): Promise<string> {
  const chunks = await retrieveRelevantChunks(userId, question, 4);

  if (chunks.length === 0) {
    return "در منابع بارگذاری‌شده، مطلب مرتبطی پیدا نکردم.";
  }

  const context = chunks
    .map(
      (chunk, index) =>
        `[منبع ${index + 1}: فایل ${chunk.filename}، صفحه PDF ${chunk.pageNumber}]\n${chunk.content}`,
    )
    .join("\n\n---\n\n");

  const response = await fetch(LLM_URL, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
    },
    signal: AbortSignal.timeout(120_000),
    body: JSON.stringify({
      model: LLM_MODEL,
      stream: false,
      messages: [
        {
          role: "system",
          content: `تو یک دستیار هوشمند تحصیلی هستی.
به زبان فارسی پاسخ بده.
از متن منابع ارائه‌شده برای پاسخ استفاده کن.
اطلاعاتی را که در منابع وجود ندارند، به‌عنوان واقعیت بیان نکن.
اگر منابع برای پاسخ کافی نیستند، صریحاً بگو.
پاسخ را واضح و مناسب یادگیری دانشجو بنویس.
نام فایل و شماره صفحه را در متن پاسخ ذکر نکن؛
منابع در انتهای پاسخ توسط برنامه اضافه می‌شوند.
اگر متن استخراج‌شده نامفهوم یا ناقص است، آن را با حدس خودت تکمیل نکن.`,
        },
        {
          role: "user",
          content: `سؤال:
${question}

متن منابع:
${context}

بر اساس متن منابع به سؤال پاسخ بده.`,
        },
      ],
    }),
  });

  if (!response.ok) {
    throw new Error(
      `Ollama chat error: ${response.status} ${response.statusText}`,
    );
  }

  const data = (await response.json()) as {
    message?: { content?: string };
  };

  const answer = data.message?.content?.trim();

  if (!answer) {
    throw new Error("Ollama returned an empty answer");
  }

  // Build a unique list of sources from the retrieved chunks.
  const sources = [
    ...new Map(
      chunks
        .filter((chunk) => chunk.pageNumber != null)
        .map((chunk) => [
          `${chunk.filename}:${chunk.pageNumber}`,
          `${chunk.filename} — صفحه PDF ${chunk.pageNumber}`,
        ]),
    ).values(),
  ];

  // Return the answer without a source section if no page numbers exist.
  if (sources.length === 0) {
    return answer;
  }

  // Append citations generated by our application, not the LLM.
  return `${answer}\n\n**منابع بازیابی‌شده:**\n${sources
    .map((source) => `- ${source}`)
    .join("\n")}`;
}
